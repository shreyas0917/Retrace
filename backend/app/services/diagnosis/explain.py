"""Evidence-based, templated explanations for a diagnosis decision.

The explanation is derived only from the signal bag and the matched rule. It
is not generated by an LLM, so it can be reproduced from stored signals and
never asserts anything the engine did not observe.
"""

from __future__ import annotations

from app.services.diagnosis.models import DiagnosisDecision, SignalBag
from app.services.diagnosis.thresholds import (
    FAITHFUL_BOUNDARY_BAND,
    TAU_DISTRACTOR_FRAC,
    TAU_FAITHFUL,
    TAU_REL,
)


def _fmt_pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.0%}"


def _relevant_count(signals: SignalBag) -> int | None:
    items = signals.chunk_relevance or []
    if not items:
        return None
    count = 0
    for item in items:
        score = item.get("score")
        if item.get("relevant") is True or (
            isinstance(score, (int, float)) and float(score) >= TAU_REL
        ):
            count += 1
    return count


def build_explanation(decision: DiagnosisDecision, signals: SignalBag) -> str:
    """One paragraph: observed evidence → matched rule → outcome."""
    parts: list[str] = []

    # Infrastructure first: these short-circuit everything else.
    if signals.stage_error == "TIMEOUT":
        parts.append("The generation or judge stage timed out before producing a usable answer")
    if not signals.judge_schema_ok:
        parts.append("A required judge returned malformed output after one retry")

    # Retrieval evidence.
    if signals.n_retrieved == 0:
        parts.append("Retrieval returned no chunks")
    else:
        retrieval = f"Retrieved {signals.n_retrieved} chunk(s)"
        if signals.gold_ids:
            if signals.gold_hit:
                retrieval += (
                    f"; gold-relevant chunk(s) present "
                    f"(recall@k {signals.gold_recall_at_k:.2f})"
                    if signals.gold_recall_at_k is not None
                    else "; gold-relevant chunk(s) present"
                )
            else:
                retrieval += (
                    f"; none of the {len(signals.gold_ids)} gold-relevant chunk(s) "
                    "appeared in the top-k"
                )
        parts.append(retrieval)

    # Relevance judge.
    if signals.context_sufficient is not None:
        rel_count = _relevant_count(signals)
        rel = "relevance judge"
        if rel_count is not None:
            rel += f" marked {rel_count}/{signals.n_retrieved} chunk(s) relevant"
        if signals.irrelevant_frac is not None:
            rel += f" ({_fmt_pct(signals.irrelevant_frac)} irrelevant"
            if signals.irrelevant_frac >= TAU_DISTRACTOR_FRAC:
                rel += f", at or above the {TAU_DISTRACTOR_FRAC:.0%} distractor threshold"
            rel += ")"
        rel += " and judged the context " + (
            "sufficient" if signals.context_sufficient else "insufficient"
        )
        parts.append(rel)

    # Answer behaviour.
    parts.append(
        "The system abstained" if signals.answer_is_abstention else "The system answered"
    )

    # Grounding judges.
    faith = signals.faithfulness_score
    if (
        signals.context_sufficient is True
        and not signals.answer_is_abstention
        and faith is not None
    ):
        supported = signals.supported_claim_count or 0
        unsupported = signals.unsupported_claim_count or 0
        grounding = (
            f"faithfulness {faith:.2f} with {supported} supported / "
            f"{unsupported} unsupported claim(s)"
        )
        if abs(faith - TAU_FAITHFUL) <= FAITHFUL_BOUNDARY_BAND:
            grounding += f" (within {FAITHFUL_BOUNDARY_BAND:.2f} of the {TAU_FAITHFUL:.2f} threshold)"
        parts.append(grounding)
        if signals.answer_contradicts_context is not None:
            parts.append(
                "the contradiction judge found a conflict with the context"
                if signals.answer_contradicts_context
                else "the contradiction judge found no conflict"
            )

    conclusion = (
        f"Rule {decision.rule_id} therefore classifies this as "
        f"{decision.primary_code} ({decision.diagnosis_confidence} confidence, "
        f"score {decision.diagnosis_score:.2f})"
    )
    if decision.secondary_codes:
        conclusion += f"; secondary: {', '.join(decision.secondary_codes)}"
    if decision.primary_code == "DIAGNOSIS_UNCERTAIN":
        conclusion += ". The judge outputs do not support a confident localization; manual review is recommended"

    body = "; ".join(parts)
    return f"{body}. {conclusion}."
